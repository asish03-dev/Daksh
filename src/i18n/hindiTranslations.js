/**
 * Universal Quiz Localization Helper
 */
export function getLocalizedQuiz(quiz, lang) {
  if (lang !== "hi" || !quiz) return quiz;
  const courseHi = COURSE_HI_MAP[quiz.courseId];
  const compHi = COMPETENCY_HI_MAP[quiz.competencyCode];

  const localizedTitle = courseHi?.title 
    ? `${courseHi.title} - आधिकारिक मूल्यांकन` 
    : (quiz.title_hi || quiz.title);

  return {
    ...quiz,
    title: localizedTitle,
    competencyName: compHi?.name || quiz.competencyName,
    difficulty: quiz.difficulty ? quiz.difficulty.replace("Advanced", "उन्नत").replace("Intermediate", "मध्यम").replace("Foundation", "बुनियादी") : quiz.difficulty,
  };
}
